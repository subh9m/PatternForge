    category: "VECTORS",
    definition: "A dense array of high-dimensional numbers generated by a model to capture and represent the semantic meaning of data.",
    analogy: "A latitude/longitude coordinate pair, but instead of mapping global geography, it maps semantic human meanings.",
    oneLiner: "Embeddings represent conceptual meaning as mathematical coordinates in high-dimensional space."
